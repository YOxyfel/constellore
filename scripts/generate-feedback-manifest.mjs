import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { authoredRecipeCatalog } from "../server.mjs";

const outputPath = resolve("workers/feedback/generated/review-manifest.mjs");
const packageData = JSON.parse(await readFile(resolve("package.json"), "utf8"));

function conceptKey(value) {
  return String(value || "").normalize("NFKC").trim().toLocaleLowerCase("en");
}

function pairKey(left, right) {
  return [conceptKey(left), conceptKey(right)].sort().join("\0");
}

const recipes = authoredRecipeCatalog();
const concepts = new Map([
  ["earth", "Earth"],
  ["water", "Water"],
  ["fire", "Fire"],
  ["air", "Air"]
]);
const authoredPairs = new Set();

for (const recipe of recipes) {
  for (const word of [recipe.a, recipe.b, recipe.word]) {
    const key = conceptKey(word);
    if (key && !concepts.has(key)) concepts.set(key, String(word).normalize("NFKC").trim());
  }
  authoredPairs.add(pairKey(recipe.a, recipe.b));
}

const conceptEntries = [...concepts]
  .sort(([left], [right]) => left.localeCompare(right, "en"));
const pairEntries = [...authoredPairs]
  .sort((left, right) => left.localeCompare(right, "en"));

const source = `// Generated by scripts/generate-feedback-manifest.mjs. Do not edit by hand.
export const FEEDBACK_GRAPH_VERSION = ${JSON.stringify(`world-${packageData.version}`)};
export const REVIEW_CONCEPTS = new Map(${JSON.stringify(conceptEntries)});
export const AUTHORED_PAIR_KEYS = new Set(${JSON.stringify(pairEntries)});
`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, source, "utf8");
console.log(`Generated feedback review manifest: ${conceptEntries.length} concepts, ${pairEntries.length} authored pairs.`);
